import { mkdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import vm from "node:vm";
import ts from "typescript";

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const root = path.resolve(__dirname, "..");

const GROUP_IDS = ["A", "B", "C", "D", "E", "F", "G", "H", "I", "J", "K", "L"];

async function loadTypeScriptModule(relativePath) {
  const filename = path.join(root, relativePath);
  const source = await readFile(filename, "utf8");
  const compiled = ts.transpileModule(source, {
    compilerOptions: {
      esModuleInterop: true,
      module: ts.ModuleKind.CommonJS,
      target: ts.ScriptTarget.ES2020,
    },
    fileName: filename,
  }).outputText;

  const module = { exports: {} };
  const context = vm.createContext({
    console,
    exports: module.exports,
    module,
    require(id) {
      throw new Error(`Unsupported require("${id}") while loading ${relativePath}`);
    },
  });

  new vm.Script(compiled, { filename }).runInContext(context);
  return module.exports;
}

function sqlValue(value) {
  if (value === null || value === undefined) return "null";
  if (typeof value === "number") return String(value);
  if (typeof value === "boolean") return value ? "true" : "false";
  return `'${String(value).replaceAll("'", "''")}'`;
}

function valuesFor(columns, rows) {
  return rows
    .map((row) => `  (${columns.map((column) => sqlValue(row[column])).join(", ")})`)
    .join(",\n");
}

function upsert(table, columns, rows, conflictColumns, updateColumns) {
  const updates =
    updateColumns ?? columns.filter((column) => !conflictColumns.includes(column));
  const conflict = conflictColumns.join(", ");
  const action = updates.length
    ? `do update\nset\n${updates
        .map((column) => `  ${column} = excluded.${column}`)
        .join(",\n")}`
    : "do nothing";

  return `insert into public.${table} (${columns.join(", ")})\nvalues\n${valuesFor(
    columns,
    rows
  )}\non conflict (${conflict}) ${action};`;
}

function bracketNodes(matches) {
  const counters = new Map();
  return matches
    .filter((match) => match.r !== "GS")
    .map((match) => {
      const rowIndex = counters.get(match.r) ?? 0;
      counters.set(match.r, rowIndex + 1);
      return {
        match_n: match.n,
        round: match.r,
        column_index: ["R32", "R16", "QF", "SF", "3P", "F"].indexOf(match.r),
        row_index: rowIndex,
        label: `Match ${match.n}`,
      };
    });
}

function bracketConnections(matches) {
  const connections = [];
  for (const source of matches) {
    for (const target of matches) {
      if (target.h === `W${source.n}` || target.a === `W${source.n}`) {
        connections.push({
          from_match_n: source.n,
          to_match_n: target.n,
          connection_type: "winner",
        });
      }
      if (target.h === `L${source.n}` || target.a === `L${source.n}`) {
        connections.push({
          from_match_n: source.n,
          to_match_n: target.n,
          connection_type: "loser",
        });
      }
    }
  }
  return connections;
}

const { MATCH_STAGES } = await loadTypeScriptModule("src/data/stages.ts");
const { TEAMS } = await loadTypeScriptModule("src/data/teams.ts");
const { VENUES } = await loadTypeScriptModule("src/data/venues.ts");
const { MATCHES } = await loadTypeScriptModule("src/data/matches.ts");

const groups = GROUP_IDS.map((id) => ({
  id,
  name_en: `Group ${id}`,
  name_ar: `\u0627\u0644\u0645\u062c\u0645\u0648\u0639\u0629 ${id}`,
}));

const stages = MATCH_STAGES.map((stage) => ({
  id: stage.id,
  name_en: stage.nameEn,
  name_ar: stage.nameAr,
  stage_order: stage.stageOrder,
  is_knockout: stage.isKnockout,
}));

const teams = TEAMS.map((team) => ({
  id: team.id,
  group_id: team.group,
  iso: team.iso,
  name_en: team.nameEn,
  name_ar: team.nameAr,
  host: Boolean(team.host),
}));

const venues = VENUES.map((venue) => ({
  id: venue.id,
  name_en: venue.nameEn,
  name_ar: venue.nameAr,
  city_en: venue.cityEn,
  city_ar: venue.cityAr,
  country: venue.country,
  lat: venue.lat,
  lng: venue.lng,
  tz: venue.tz,
  capacity: venue.capacity,
}));

const matches = MATCHES.map((match) => ({
  match_n: match.n,
  round: match.r,
  group_id: match.g ?? null,
  home_slot: match.h,
  away_slot: match.a,
  kickoff_at: match.t,
  venue_id: match.v,
  status: "scheduled",
}));

const sections = [
  "-- Generated by npm run seed:sql. Do not edit by hand.",
  "-- Apply after migrations have created the schema.",
  "begin;",
  upsert(
    "match_stages",
    ["id", "name_en", "name_ar", "stage_order", "is_knockout"],
    stages,
    ["id"]
  ),
  upsert("groups", ["id", "name_en", "name_ar"], groups, ["id"]),
  upsert(
    "teams",
    ["id", "group_id", "iso", "name_en", "name_ar", "host"],
    teams,
    ["id"]
  ),
  upsert(
    "venues",
    [
      "id",
      "name_en",
      "name_ar",
      "city_en",
      "city_ar",
      "country",
      "lat",
      "lng",
      "tz",
      "capacity",
    ],
    venues,
    ["id"]
  ),
  upsert(
    "matches",
    [
      "match_n",
      "round",
      "group_id",
      "home_slot",
      "away_slot",
      "kickoff_at",
      "venue_id",
      "status",
    ],
    matches,
    ["match_n"]
  ),
  upsert(
    "bracket_nodes",
    ["match_n", "round", "column_index", "row_index", "label"],
    bracketNodes(MATCHES),
    ["match_n"]
  ),
  upsert(
    "bracket_connections",
    ["from_match_n", "to_match_n", "connection_type"],
    bracketConnections(MATCHES),
    ["from_match_n", "to_match_n", "connection_type"],
    []
  ),
  "commit;",
];

await mkdir(path.join(root, "supabase"), { recursive: true });
await writeFile(path.join(root, "supabase", "seed.sql"), `${sections.join("\n\n")}\n`, "utf8");
