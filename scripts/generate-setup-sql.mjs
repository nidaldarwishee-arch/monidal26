/**
 * Bundles every migration plus the generated seed into one SQL file
 * (supabase/setup.generated.sql) that can be pasted once into the
 * Supabase Dashboard SQL editor to provision an empty project.
 */
import { readdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { projectRoot } from "./lib/schedule-data.mjs";

const migrationsDir = path.join(projectRoot, "supabase", "migrations");
const migrationFiles = (await readdir(migrationsDir))
  .filter((name) => name.endsWith(".sql"))
  .sort();

if (migrationFiles.length === 0) {
  throw new Error(`No migrations found in ${migrationsDir}`);
}

const parts = [
  "-- Generated by npm run db:setup-sql. Do not edit by hand.",
  "-- One-paste provisioning for an empty Supabase project:",
  "-- all migrations in order, followed by the generated seed data.",
];

for (const name of migrationFiles) {
  parts.push(`\n-- ── migration: ${name} ${"─".repeat(Math.max(8, 60 - name.length))}\n`);
  parts.push((await readFile(path.join(migrationsDir, name), "utf8")).trimEnd());
}

parts.push(`\n-- ── seed: seed.sql ${"─".repeat(42)}\n`);
parts.push(
  (await readFile(path.join(projectRoot, "supabase", "seed.sql"), "utf8")).trimEnd()
);

const outFile = path.join(projectRoot, "supabase", "setup.generated.sql");
await writeFile(outFile, `${parts.join("\n")}\n`, "utf8");
console.log(`Wrote ${path.relative(projectRoot, outFile)} (${migrationFiles.length} migrations + seed).`);
